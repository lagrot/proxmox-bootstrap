const assert=require('node:assert/strict');
require('../static/assets/demo-core.js');
const c=globalThis.LandetDemoCore;
assert(c.validDate('2026-10-26'));
for(const value of ['2026-02-30','bad','','2026-13-01']) assert(!c.validDate(value));
assert.throws(()=>c.history({id:'x'},'bad'));
assert.throws(()=>c.clips([],'2026-10-26'));
const room={id:'living',temperature:11,humidity:60};
const points=c.history(room,'2026-10-26');
assert.equal(points.temperatures.length,97);
assert.deepEqual(points,c.history(room,'2026-10-26'));
assert.notDeepEqual(points,c.history(room,'2026-10-25'));
assert.equal(c.history({id:'out',temperature:10},'2026-10-26').humidity.length,0);
const clips=c.clips([{id:'a',name:'A'},{id:'b',name:'B'}],'2026-10-26');
assert.equal(clips.length,12);
assert(clips.every((v,i)=>!i || clips[i-1].started>v.started));
assert.equal(c.duration(75),'01:15');
assert.equal(c.escape('<script>'),'&lt;script&gt;');
console.log('PASS: deterministic sample history, invalid dates/configuration, outdoor humidity absence, 12 descending clips, escaping and durations.');
